// Renders the Radar's published issues into `src/generated/radar/` so the page
// and each issue's page carry their content in the HTML (search engines, link
// previews and crawlers read the HTML, not what a script fetches later). Runs in
// `pnpm gen` after the lab generator. Only published digests are ever read: the
// public endpoint serves no drafts, and they are filtered here again. When the
// radar cannot be reached (an offline build, a checkout with no cluster) it
// writes an empty list and says so; the page then fetches in the browser as
// before, and the build never fails for want of the network.
//
//   RADAR_SOURCE_URL=https://inorbit.hr node --no-warnings tool/radar-data.ts

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import type { RadarDigest, RadarIssue } from "../src/lib/radar.ts";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../src/generated/radar");
const source = (process.env.RADAR_SOURCE_URL ?? "https://inorbit.hr").replace(/\/$/, "");

async function published(): Promise<RadarDigest[]> {
  try {
    const res = await fetch(`${source}/v1/radar/digests?limit=500`, {
      headers: { accept: "application/json", "user-agent": "tbd-www-build" },
      signal: AbortSignal.timeout(15_000),
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const body = (await res.json()) as { digests?: RadarDigest[] };
    return (body.digests ?? []).filter((d) => d.status === "published" && !d.stub);
  } catch (e) {
    console.warn(
      `radar: ${source} not reachable (${(e as Error).message}); no issues rendered, the page fetches in the browser`,
    );
    return [];
  }
}

const digests = await published();
// Issues are weeks. Only reviewed live weeks are numbered, in order; archive
// weeks (the backfill, not individually reviewed) have pages but no number.
const weeks = [...new Set(digests.map((d) => d.week))].sort();
let n = 0;
const issues: RadarIssue[] = weeks
  .map((week) => {
    const ofWeek = digests.filter((d) => d.week === week);
    const live = ofWeek.some((d) => d.origin !== "archive");
    return { number: live ? ++n : null, week, slug: week.toLowerCase(), digests: ofWeek };
  })
  .reverse();

mkdirSync(out, { recursive: true });
writeFileSync(
  join(out, "index.ts"),
  `// Generated by tool/radar-data.ts from ${source}. Do not edit; run \`pnpm gen\`.
import type { RadarIssue } from "@/lib/radar";

export const issues: RadarIssue[] = ${JSON.stringify(issues, null, 2)};
`,
);
console.log(
  `radar: ${issues.length} issue${issues.length === 1 ? "" : "s"}, ${digests.length} digests -> ${out}`,
);
